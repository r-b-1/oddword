import type { Answer, Question } from '../types/game';
import { calculateDepth, calculatePoints, getTier } from '../types/game';

type Row = [text: string, rarity: number, aliases?: string[]];

function answer(text: string, rarity: number, aliases: string[] = []): Answer {
  const points = calculatePoints(rarity);
  return {
    text,
    aliases,
    rarity,
    points,
    tier: getTier(points),
    depth: calculateDepth(points),
  };
}

function question(id: string, category: string, prompt: string, rows: Row[]): Question {
  return {
    id,
    category,
    prompt,
    answers: rows.map(([text, rarity, aliases]) => answer(text, rarity, aliases ?? [])),
  };
}

